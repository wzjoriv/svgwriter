def targets() -> list[type]:
    """Every registered element class defined in ``svgwriter.model.elements``."""
    import svgwriter
    from svgwriter.model.elements import Element

    if Path(svgwriter.__file__).resolve().parent != PACKAGE:
        raise SystemExit(f"svgwriter is imported from {Path(svgwriter.__file__).parent}, not {PACKAGE}; set PYTHONPATH")

    found = {cls for cls in Element._registry.values() if cls.__module__.startswith("svgwriter.model.elements.")}
    return sorted(found, key=lambda c: (c.__module__, _class_node(c).lineno))


def _forward_source() -> str:
    module = "svgwriter.model.elements.core._forward"
    params = common_params()
    needed: dict[str, set[str]] = {"typing": {"TYPE_CHECKING", "Any"}}
    type_only: dict[str, set[str]] = {}
    plain: set[str] = set()
    for param in params:
        for name in _annotation_names(param.annotation):
            if name == "Any":
                continue
            found = _import_for(module, param.home, name)
            if found is None:
                continue
            if found[0] == "import":
                plain.add(found[1])
            else:
                type_only.setdefault(found[0], set()).add(found[1])
    head = render_imports(module, needed, set(), indent="")
    tail = render_imports(module, type_only, plain)
    imports = "\n".join([*head, "", "if TYPE_CHECKING:", *tail])
    return render_forward(params).replace("{imports}", imports)


def generate() -> dict[Path, str]:
    """New contents of every file the generator owns, keyed by path."""
    _TREES.clear()
    found = targets()
    target_set = set(found)
    by_module: dict[str, list[Plan]] = {}
    for cls in found:
        by_module.setdefault(cls.__module__, []).append(plan(cls, target_set))
    out = {FORWARD_MODULE: _forward_source()}
    for module, plans in by_module.items():
        out[_module_path(module)] = rewrite_module(module, plans)
    return out


def write() -> list[Path]:
    """Regenerate every region; return the files that changed."""
    changed = []
    for path, text in generate().items():
        if not path.exists() or path.read_text(encoding="utf-8") != text:
            path.write_text(text, encoding="utf-8", newline="\n")
            changed.append(path)
    return changed


def check() -> list[Path]:
    """Files whose generated regions are stale."""
    return [path for path, text in generate().items()
            if not path.exists() or path.read_text(encoding="utf-8") != text]
