"""Generate the typed ``__init__`` of every element class from the attribute-group signatures.

Each registered element class gets an ``__init__`` that lists its own
parameters, every keyword of the attribute groups it inherits (the
cooperative ``__init__`` of each base, plus `PresentationKeywords` for
presentation elements) and ``**kwargs``. The generated code forwards the
keywords that were given into ``kwargs`` and hands over to the existing
initialisation, so behaviour does not change; editors, ``help`` and the
stubs see the full list.

Generated code sits between ``# region generated`` and ``# endregion``
markers. A class whose own ``__init__`` does real work keeps that work after
the ``# endregion`` line inside the method; the generator only rewrites the
signature, the docstring and the forwarding lines above it.
"""

from __future__ import annotations

import ast
import builtins
import importlib
import re
import textwrap
from dataclasses import dataclass, field
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
PACKAGE = ROOT / "svgwriter"
REGION = "# region generated by `python scripts/dev.py svgwriter signatures write`"
IMPORTS_REGION = REGION + ": names used by the signatures"
END = "# endregion"
FORWARD_MODULE = PACKAGE / "model" / "elements" / "core" / "_forward.py"
FORWARD_FUNCTION = "forward_common"
FORWARD_ATTRIBUTE = "_forward_common"
PRESENTATION = "PresentationAttributes"
INDENT = "    "
WRAP = 116
BUILTIN_NAMES = frozenset(dir(builtins))
STDLIB = frozenset({"typing", "collections", "collections.abc", "os", "enum", "pathlib"})
SHARED = "svgwriter._internal"
COMMON_GROUPS = ("Transformable", "PresentationAttributes", "StyleAttributes", "XLinkAttributes",
                 "ConditionalAttributes", "ExternalResourcesAttribute", "CoreAttributes", "Element")
"""The attribute groups many elements share, in the order the generated signatures list them."""
FORWARD_ORDER = ("Element", "CoreAttributes", "ConditionalAttributes", "ExternalResourcesAttribute", "XLinkAttributes",
                 "StyleAttributes", "PresentationAttributes", "Transformable")
"""The same groups in ``forward_common``'s order: rarer groups last, so calls can stop early."""


@dataclass
class Param:
    """One parameter: its source text and where its annotation's names resolve."""

    name: str
    annotation: str
    default: str | None
    home: str
    group: str = ""

    def render(self) -> str:
        text = self.name + (f": {self.annotation}" if self.annotation else "")
        if self.default is not None:
            text += f" = {self.default}" if self.annotation else f"={self.default}"
        return text


@dataclass
class Plan:
    """The generated ``__init__`` of one class."""

    cls: type
    positional: list[Param] = field(default_factory=list)
    vararg: Param | None = None
    own_keywords: list[Param] = field(default_factory=list)
    forwarded: list[Param] = field(default_factory=list)
    varkw: Param | None = None
    tail: list[str] | None = None
    call: str = ""


def _module_path(module: str) -> Path:
    path = ROOT.joinpath(*module.split("."))
    return path / "__init__.py" if path.is_dir() else path.with_suffix(".py")


_TREES: dict[str, tuple[ast.Module, str]] = {}


def _tree(module: str) -> tuple[ast.Module, str]:
    if module not in _TREES:
        source = _module_path(module).read_text(encoding="utf-8")
        _TREES[module] = (ast.parse(source), source)
    return _TREES[module]


def _class_node(cls: type) -> ast.ClassDef:
    tree, _ = _tree(cls.__module__)
    for node in tree.body:
        if isinstance(node, ast.ClassDef) and node.name == cls.__name__:
            return node
    raise LookupError(f"{cls.__module__}.{cls.__name__} not found at module level")


def _init_node(cls: type) -> ast.FunctionDef | None:
    for node in _class_node(cls).body:
        if isinstance(node, ast.FunctionDef) and node.name == "__init__":
            return node
    return None


def _param(arg: ast.arg, default: ast.expr | None, source: str, home: str) -> Param:
    annotation = ast.get_source_segment(source, arg.annotation) if arg.annotation else ""
    value = ast.get_source_segment(source, default) if default is not None else None
    return Param(arg.arg, annotation or "", value, home)


def _signature(cls: type) -> tuple[list[Param], Param | None, list[Param], Param | None]:
    """Positional parameters, ``*args``, keyword-only parameters and ``**kwargs`` of *cls*'s own ``__init__``."""
    node = _init_node(cls)
    assert node is not None
    _, source = _tree(cls.__module__)
    home = cls.__module__
    args = node.args
    plain = args.posonlyargs + args.args
    defaults: list[ast.expr | None] = [None] * (len(plain) - len(args.defaults)) + list(args.defaults)
    positional = [_param(a, d, source, home) for a, d in zip(plain, defaults, strict=True)][1:]
    keywords = [_param(a, d, source, home) for a, d in zip(args.kwonlyargs, args.kw_defaults, strict=True)]
    vararg = _param(args.vararg, None, source, home) if args.vararg else None
    varkw = _param(args.kwarg, None, source, home) if args.kwarg else None
    return positional, vararg, keywords, varkw


def _region_bounds(lines: list[str], start: int, stop: int) -> tuple[int, int] | None:
    """Line indexes of the region and end markers between *start* and *stop*, if present."""
    begin = next((i for i in range(start, stop) if lines[i].strip() == REGION), None)
    if begin is None:
        return None
    end = next(i for i in range(begin, len(lines)) if lines[i].strip() == END)
    return begin, end


def _tail(cls: type) -> list[str] | None:
    """The hand-written statements of *cls*'s ``__init__``, or None if the whole method is generated."""
    node = _init_node(cls)
    if node is None:
        return None
    _, source = _tree(cls.__module__)
    lines = source.splitlines()
    bounds = _region_bounds(lines, _class_node(cls).lineno, node.end_lineno or node.lineno)
    if bounds is not None:
        _, end = bounds
        if not lines[end].startswith(INDENT * 2):
            return None
        return lines[end + 1:node.end_lineno]
    body = node.body
    if body and isinstance(body[0], ast.Expr) and isinstance(body[0].value, ast.Constant):
        body = body[1:]
    return lines[body[0].lineno - 1:node.end_lineno]


def _names_in(lines: list[str]) -> set[str]:
    """Names the statements read before assigning them: the parameters a hand-written body uses."""
    tree = ast.parse(textwrap.dedent("\n".join(lines)))
    stored: set[str] = set()
    loaded: set[str] = set()

    def visit(statement: ast.stmt) -> None:
        parts = [c for c in ast.iter_child_nodes(statement) if not isinstance(c, ast.stmt)]
        names = [n for part in parts for n in ast.walk(part) if isinstance(n, ast.Name)]
        loaded.update(n.id for n in names if isinstance(n.ctx, ast.Load) and n.id not in stored)
        stored.update(n.id for n in names if isinstance(n.ctx, ast.Store))
        for child in ast.iter_child_nodes(statement):
            if isinstance(child, ast.stmt):
                visit(child)

    for statement in tree.body:
        visit(statement)
    return loaded


def _providers(cls: type, targets: set[type]) -> list[type]:
    """The attribute-group bases of *cls*: hand-written ``__init__`` methods, not generated ones."""
    return [base for base in cls.__mro__[1:]
            if "__init__" in base.__dict__ and base.__module__.startswith("svgwriter.") and base not in targets]


def _keywords_class() -> type:
    from svgwriter.model.elements._behavior._presentation import PresentationKeywords

    return PresentationKeywords


def _typed_dict_params(cls: type) -> list[Param]:
    _, source = _tree(cls.__module__)
    params = []
    for node in _class_node(cls).body:
        if isinstance(node, ast.AnnAssign) and isinstance(node.target, ast.Name):
            params.append(Param(node.target.id, ast.get_source_segment(source, node.annotation) or "", None,
                                cls.__module__))
    return params


def _group_params(provider: type) -> list[Param]:
    """The keywords an attribute-group base takes: its ``__init__`` parameters (and `PresentationKeywords`)."""
    positional, _, keywords, _ = _signature(provider)
    params = positional + keywords
    if provider.__name__ == PRESENTATION:
        params += _typed_dict_params(_keywords_class())
    return params


def _group_rank(provider: type) -> int:
    """Element-specific groups first, in MRO order, then the common groups in a fixed order."""
    return COMMON_GROUPS.index(provider.__name__) + 1 if provider.__name__ in COMMON_GROUPS else 0


def _optional(annotation: str) -> str:
    """*annotation* accepting None, since every generated keyword defaults to None."""
    if not annotation or re.search(r"\bNone\b|\bAny\b", annotation):
        return annotation
    return f"{annotation} | None"


def plan(cls: type, targets: set[type]) -> Plan:
    """Work out the generated ``__init__`` of *cls*."""
    result = Plan(cls)
    tail = _tail(cls)
    nearest = next(b for b in cls.__mro__[1:] if "__init__" in b.__dict__)
    providers = _providers(cls, targets)
    first: list[Param] = []
    if tail is not None:
        positional, vararg, keywords, varkw = _signature(cls)
        result.tail = tail
        used = _names_in(tail)
        own_keywords = [p for p in keywords if p.name in used]
    elif nearest in targets:
        inner = plan(nearest, targets)
        positional, vararg, varkw = inner.positional, inner.vararg, inner.varkw
        own_keywords = []
        first = inner.own_keywords
        for p in first:
            p.group = nearest.__name__
    else:
        positional, vararg, _, varkw = _signature(nearest)
        own_keywords = []
    result.positional, result.vararg, result.own_keywords = positional, vararg, own_keywords
    result.varkw = varkw or Param("kwargs", "Any", None, "typing")
    taken = {p.name for p in [*positional, *own_keywords]} | {p.name for p in (vararg, varkw) if p is not None}
    groups: list[list[Param]] = [first]
    for provider in sorted(providers, key=_group_rank):
        group = _group_params(provider)
        for p in group:
            p.group = provider.__name__
        groups.append(group)
    for group in groups:
        for p in group:
            if p.name in taken:
                continue
            if p.default not in (None, "None"):
                p.annotation = _optional(p.annotation)
            p.default = "None"
            taken.add(p.name)
            result.forwarded.append(p)
    if tail is not None:
        kept = taken | {p.name for p in result.forwarded}
        lost = [p.name for p in keywords if p.name not in kept]
        if lost:
            raise SystemExit(f"{cls.__name__}: keywords {lost} are neither used by __init__ nor inherited")
    pos_names = [p.name for p in positional] + ([f"*{vararg.name}"] if vararg else [])
    result.call = ", ".join([*pos_names, f"**{result.varkw.name}"])
    return result


def _public_path(cls: type) -> str | None:
    import svgwriter
    import svgwriter.model.elements

    for module in (svgwriter, svgwriter.model.elements):
        if getattr(module, cls.__name__, None) is cls:
            return f"{module.__name__}.{cls.__name__}"
    return None


def _wrap(prefix: str, names: list[str], indent: str, suffix: str = "") -> list[str]:
    lines, current = [], indent + prefix
    for index, name in enumerate(names):
        piece = name + ("," if index < len(names) - 1 or suffix else "")
        if len(current) + len(piece) + 1 > WRAP and current.strip():
            lines.append(current.rstrip())
            current = indent
        current += piece + " "
    lines.append(current.rstrip() + suffix)
    return lines


def _docstring(p: Plan, indent: str) -> list[str]:
    out = [f'{indent}"""Create a ``<{p.cls.tag}>`` element.', "", f"{indent}Parameters", f"{indent}----------"]
    own = [q.name for q in p.positional] + ([f"*{p.vararg.name}"] if p.vararg else []) + [k.name for k in p.own_keywords]
    groups: dict[str, list[str]] = {}
    for param in p.forwarded:
        groups.setdefault(param.group, []).append(param.name)
    own += [name for group, names in groups.items() if group not in COMMON_GROUPS for name in names]
    if own:
        out += [indent + ", ".join(own), f"{indent}{INDENT}See the class docstring."]
    common = [group for group in COMMON_GROUPS if group in groups]
    if common:
        classes = [_public_path(next(b for b in p.cls.__mro__ if b.__name__ == g)) for g in common]
        references = ", ".join(f":class:`~{path}`" for path in classes if path)
        out += [indent + ", ".join(name for g in common for name in groups[g]),
                f"{indent}{INDENT}The attribute groups of {references}. Defaults to None (unset)."]
    assert p.varkw is not None
    out += [f"{indent}**{p.varkw.name}",
            f"{indent}{INDENT}Any other SVG attribute in Python spelling, including namespaced and open ones",
            f"{indent}{INDENT}(``inkscape_label``, ``data_*``).",
            f'{indent}"""']
    return out


def render_init(p: Plan) -> list[str]:
    """Lines of the generated region inside a class body."""
    i1, i2, i3 = INDENT, INDENT * 2, INDENT * 3
    lines = [i1 + REGION, f"{i1}def __init__(", f"{i2}self,"]
    lines += [f"{i2}{param.render()}," for param in p.positional]
    if p.vararg:
        lines.append(f"{i2}*{p.vararg.render()},")
    elif p.own_keywords or p.forwarded:
        lines.append(f"{i2}*,")
    lines += [f"{i2}{param.render()}," for param in p.own_keywords]
    lines += [f"{i2}{param.render()}," for param in p.forwarded]
    assert p.varkw is not None
    lines += [f"{i2}**{p.varkw.render()},", f"{i1}) -> None:"]
    lines += _docstring(p, i2)
    kwargs = p.varkw.name
    for param in p.forwarded:
        if param.group not in COMMON_GROUPS:
            lines += [f"{i2}if {param.name} is not None:", f'{i3}{kwargs}["{param.name}"] = {param.name}']
    given = {param.name for param in p.forwarded if param.group in COMMON_GROUPS}
    values = [name if name in given else "None" for name in common_names()]
    while values and values[-1] == "None":
        values.pop()
    if values:
        lines += [f"{i2}self.{FORWARD_ATTRIBUTE}("] + _wrap("", [kwargs, *values], i3) + [f"{i2})"]
    if p.tail is None:
        lines += [f"{i2}super().__init__({p.call})", i1 + END]
    else:
        lines += [i2 + END, *p.tail]
    return lines


def common_params() -> list[Param]:
    """The parameters of ``forward_common``: the common attribute groups in `FORWARD_ORDER`."""
    import svgwriter.model.elements as elements
    from svgwriter.model.elements import _behavior

    params: list[Param] = []
    for name in FORWARD_ORDER:
        group = _group_params(getattr(elements, name, None) or getattr(_behavior, name))
        for param in group:
            param.group = name
            if param.default not in (None, "None"):
                param.annotation = _optional(param.annotation)
            param.default = "None"
        params += group
    return params


def common_names() -> list[str]:
    return [param.name for param in common_params()]


def render_forward(params: list[Param]) -> str:
    """Source of the module holding ``forward_common``."""
    signature = "\n".join(f"{INDENT}{param.name}: {param.annotation} = None," for param in params)
    body = "\n".join(f"{INDENT}if {param.name} is not None:\n{INDENT * 2}kwargs[\"{param.name}\"] = {param.name}"
                     for param in params)
    names = "\n".join(_wrap("", [param.name for param in params], INDENT))
    order = ", ".join(f"`{name}`" for name in FORWARD_ORDER)
    return f'''"""
``forward_common``: copy the common attribute keywords that were given into ``kwargs``.

Generated by ``python scripts/dev.py svgwriter signatures write``; do not edit.
"""

from __future__ import annotations

{{imports}}

__all__ = ["{FORWARD_FUNCTION}"]


def {FORWARD_FUNCTION}(
{INDENT}kwargs: dict[str, Any],
{signature}
) -> None:
{INDENT}"""Add each common attribute value that is not None to *kwargs*, in parameter order.

{INDENT}The generated element constructors call it positionally, as
{INDENT}``self._forward_common(kwargs, ...)``, passing None for the groups the
{INDENT}element does not have; a positional call with inline checks is faster
{INDENT}than a loop over names.

{INDENT}Parameters
{INDENT}----------
{INDENT}kwargs : dict
{INDENT}    The keywords being forwarded; updated in place.
{names}
{INDENT}    The keywords of {order}, None when not given.

{INDENT}Examples
{INDENT}--------
{INDENT}>>> from svgwriter.model.elements.core._forward import forward_common
{INDENT}>>> given = {{}}
{INDENT}>>> forward_common(given, id="a", class_="b", stroke=None)
{INDENT}>>> given
{INDENT}{{'id': 'a', 'class_': 'b'}}
{INDENT}"""
{body}
'''


# ---- imports -------------------------------------------------------------------------------------------------


def _module_level(tree: ast.Module) -> list[ast.stmt]:
    nodes: list[ast.stmt] = []
    for node in tree.body:
        nodes.append(node)
        if isinstance(node, ast.If):
            nodes += node.body + node.orelse
    return nodes


def _bound_names(tree: ast.Module) -> set[str]:
    names: set[str] = set()
    for node in _module_level(tree):
        if isinstance(node, (ast.Import, ast.ImportFrom)):
            names |= {(a.asname or a.name).split(".")[0] for a in node.names}
    for node in tree.body:
        if isinstance(node, (ast.ClassDef, ast.FunctionDef)):
            names.add(node.name)
        elif isinstance(node, (ast.Assign, ast.AnnAssign)):
            targets = node.targets if isinstance(node, ast.Assign) else [node.target]
            names |= {t.id for t in targets if isinstance(t, ast.Name)}
    return names


def _absolute(module: str, node: ast.ImportFrom) -> str:
    if not node.level:
        return node.module or ""
    is_package = _module_path(module).name == "__init__.py"
    parts = module.split(".")
    base = parts if is_package else parts[:-1]
    base = base[: len(base) - node.level + 1]
    return ".".join(base + ([node.module] if node.module else []))


def _origin(module: str, name: str) -> tuple[str, str | None]:
    """Where *name*, as used in *module*, comes from: ``(module, None)`` or ``("import", statement)``."""
    tree, _ = _tree(module)
    for node in _module_level(tree):
        if isinstance(node, ast.ImportFrom):
            for alias in node.names:
                if (alias.asname or alias.name) == name:
                    return _absolute(module, node), alias.name
        elif isinstance(node, ast.Import):
            for alias in node.names:
                if (alias.asname or alias.name.split(".")[0]) == name:
                    text = f"import {alias.name}" + (f" as {alias.asname}" if alias.asname else "")
                    return "import", text
    return module, name


def _private(part: str) -> bool:
    return part.startswith("_") and not (part.startswith("__") and part.endswith("__"))


def _allowed(importer: str, target: str) -> bool:
    parts = target.split(".")
    for index in range(1, len(parts)):
        if not _private(parts[index]) or ".".join(parts[:index + 1]).startswith(SHARED):
            continue
        holder = ".".join(parts[:index])
        owner = holder if _module_path(holder).name == "__init__.py" else holder.rpartition(".")[0]
        if importer != owner and not importer.startswith(owner + "."):
            return False
    return True


def _import_for(importer: str, home: str, name: str) -> tuple[str, str] | None:
    """``(module, name)`` to import *name* (as used in *home*) into *importer*, or None if built in."""
    if name in BUILTIN_NAMES and name not in _bound_names(_tree(home)[0]):
        return None
    module, original = _origin(home, name)
    if module == "import":
        return ("import", original or "")
    if module in ("typing", "collections.abc", "__future__") or not module.startswith("svgwriter"):
        return module, original or name
    target = importlib.import_module(module)
    obj = getattr(target, original or name, None)
    if obj is None:
        return _import_for(importer, module, original or name)
    candidates = [module]
    parts = module.split(".")
    candidates += [".".join(parts[:i]) for i in range(len(parts) - 1, 1, -1)]
    for candidate in candidates:
        if _allowed(importer, candidate) and getattr(importlib.import_module(candidate), original or name, None) is obj:
            return candidate, original or name
    raise LookupError(f"no importable path to {name} for {importer}")


def _relative(importer: str, module: str) -> str:
    if not module.startswith("svgwriter"):
        return module
    is_package = _module_path(importer).name == "__init__.py"
    base = importer.split(".") if is_package else importer.split(".")[:-1]
    target = module.split(".")
    common = 0
    while common < min(len(base), len(target)) and base[common] == target[common]:
        common += 1
    dots = "." * (len(base) - common + 1)
    return dots + ".".join(target[common:])


def _isort_key(name: str) -> tuple[int, str]:
    if name.isupper() and len(name) > 1:
        return (0, name)
    return (1, name) if name[:1].isupper() else (2, name)


def render_imports(importer: str, needed: dict[str, set[str]], plain: set[str], indent: str = INDENT) -> list[str]:
    """``import`` lines in sections, sorted the way ruff's isort sorts them."""
    def from_line(module: str, names: set[str], spelled: str) -> str:
        return f"{indent}from {spelled} import {', '.join(sorted(names, key=_isort_key))}"

    stdlib = [from_line(m, n, m) for m, n in sorted(needed.items()) if m in STDLIB]
    third = [indent + line for line in sorted(plain)]
    third += [from_line(m, n, m) for m, n in sorted(needed.items()) if m not in STDLIB and not m.startswith("svgwriter")]
    local = sorted((m for m in needed if m.startswith("svgwriter")),
                   key=lambda m: (-_dots(_relative(importer, m)), _relative(importer, m).lstrip(".")))
    first = [from_line(m, needed[m], _relative(importer, m)) for m in local]
    out: list[str] = []
    for section in (stdlib, third, first):
        if section:
            out += ([""] if out else []) + section
    return out


def _dots(spelled: str) -> int:
    return len(spelled) - len(spelled.lstrip("."))


def _annotation_names(text: str) -> set[str]:
    if not text:
        return set()
    tree = ast.parse(text, mode="eval")
    return {n.id for n in ast.walk(tree) if isinstance(n, ast.Name)}


# ---- module rewriting ----------------------------------------------------------------------------------------


def rewrite_module(module: str, plans: list[Plan]) -> str:
    """The new source of *module* with every class's region and the import region regenerated."""
    path = _module_path(module)
    source = path.read_text(encoding="utf-8")
    lines = source.splitlines()
    edits: list[tuple[int, int, list[str]]] = []
    for p in plans:
        cls_node = _class_node(p.cls)
        init = _init_node(p.cls)
        new = render_init(p)
        if init is not None:
            start = (init.decorator_list[0].lineno if init.decorator_list else init.lineno) - 1
            bounds = _region_bounds(lines, cls_node.lineno, init.end_lineno or init.lineno)
            stop = init.end_lineno or start + 1
            if bounds is not None:
                start, stop = bounds[0], max(stop, bounds[1] + 1)
            edits.append((start, stop, new))
        else:
            first = next((n for n in cls_node.body if isinstance(n, (ast.FunctionDef, ast.AsyncFunctionDef))), None)
            if first is not None:
                at = (first.decorator_list[0].lineno if first.decorator_list else first.lineno) - 1
                edits.append((at, at, [*new, ""]))
            else:
                at = cls_node.end_lineno or cls_node.lineno
                edits.append((at, at, ["", *new]))
    for start, stop, new in sorted(edits, reverse=True):
        lines[start:stop] = new
    text = "\n".join(lines) + "\n"
    return _with_imports(module, text, plans)


def _with_imports(module: str, text: str, plans: list[Plan]) -> str:
    lines = text.splitlines()
    begin = next((i for i, line in enumerate(lines) if line.strip() == IMPORTS_REGION), None)
    if begin is not None:
        end = next(i for i in range(begin, len(lines)) if lines[i].strip() == END)
        del lines[begin:end + 2 if end + 1 < len(lines) and not lines[end + 1].strip() else end + 1]
    tree = ast.parse("\n".join(lines))
    bound = _bound_names(tree)
    needed: dict[str, set[str]] = {}
    plain: set[str] = set()
    for p in plans:
        params = list(p.forwarded)
        if p.vararg is not None and p.vararg.home != module:
            params.append(p.vararg)
        params += [q for q in p.positional if q.home != module]
        if p.varkw is not None:
            params.append(p.varkw)
        for param in params:
            for name in _annotation_names(param.annotation):
                if name in bound:
                    continue
                found = _import_for(module, param.home if param.home != "typing" else "typing", name) \
                    if param.home != "typing" else ("typing", name)
                if found is None:
                    continue
                if found[0] == "import":
                    plain.add(found[1])
                else:
                    needed.setdefault(found[0], set()).add(found[1])
    if not needed and not plain:
        return "\n".join(lines) + "\n"
    if "TYPE_CHECKING" not in bound:
        index = next((i for i, line in enumerate(lines) if line.startswith("from typing import ")), None)
        if index is None or "(" in lines[index]:
            raise SystemExit(f"{module}: import TYPE_CHECKING from typing so the generated imports can use it")
        names = {n.strip() for n in lines[index].removeprefix("from typing import ").split(",")} | {"TYPE_CHECKING"}
        lines[index] = "from typing import " + ", ".join(sorted(names, key=_isort_key))
    block = [IMPORTS_REGION, "if TYPE_CHECKING:", *render_imports(module, needed, plain), END, ""]
    at = _after_imports(tree)
    lines[at:at] = ["", *block] if lines[at - 1].strip() else block
    while at + len(block) + 1 < len(lines) and not lines[at + len(block) + 1].strip() \
            and not lines[at + len(block)].strip():
        del lines[at + len(block)]
    return "\n".join(lines) + "\n"


def _after_imports(tree: ast.Module) -> int:
    last = 0
    for node in tree.body:
        if isinstance(node, (ast.Import, ast.ImportFrom)):
            last = node.end_lineno or node.lineno
        elif isinstance(node, ast.If) and "TYPE_CHECKING" in ast.unparse(node.test):
            last = node.end_lineno or node.lineno
        elif isinstance(node, ast.Expr) and isinstance(node.value, ast.Constant) and last == 0:
            continue
        else:
            break
    return last


